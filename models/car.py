class Car:
    def __init__(
        self,
        city,
        make,
        model,
        year,
        fuel,
        seats,
        car_class,
        registration_number,
        price
    ):
        self.city = city
        self.make = make
        self.model = model
        self.year = year
        self.fuel = fuel
        self.seats = seats
        self.car_class = car_class
        self.registration_number = registration_number
        self.price = price